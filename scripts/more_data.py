def main():
    categories, guides, items = load("categories.json"), load("guides.json"), load("items.json")
    known = {c["id"] for c in categories}
    categories += [{"id": i, "name": n, "description": d, "icon": e} for i, n, d, e in CATEGORIES if i not in known]
    known = {g["id"] for g in guides}
    guides += [g for g in GUIDES if g["id"] not in known]
    known = {i["id"] for i in items}
    items += [i for i in ITEMS if i["id"] not in known]

    # nothing may point at a guide or category that is not there, and red never gets a guide
    guide_ids, category_ids = {g["id"] for g in guides}, {c["id"] for c in categories}
    for i in items:
        assert i["categoryId"] in category_ids, i["id"]
        assert i.get("guideId") is None or i["guideId"] in guide_ids, i["id"]
        assert not (i["baseSafety"] == "red" and i.get("guideId")), i["id"]
        assert (i["baseSafety"] == "red") == bool(i.get("dangerous")), i["id"]
    assert len({i["id"] for i in items}) == len(items) and len(guide_ids) == len(guides)
    used = {i.get("guideId") for i in items}
    print("guides nobody links to:", sorted(guide_ids - used))

    save("categories.json", categories)
    save("guides.json", guides)
    save("items.json", items)
    print(len(categories), "categories,", len(guides), "guides,", len(items), "items")


main()
