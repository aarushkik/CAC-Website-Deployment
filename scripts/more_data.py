"""Adds more categories, guides and items to src/data. Run once: python3 scripts/more_data.py
Existing entries are kept as they are; an id that is already there is not written twice."""
import json
import os

DATA = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "data")


def load(name):
    with open(os.path.join(DATA, name)) as f:
        return json.load(f)


def save(name, rows):
    with open(os.path.join(DATA, name), "w") as f:
        json.dump(rows, f, indent=2, ensure_ascii=False)
        f.write("\n")


